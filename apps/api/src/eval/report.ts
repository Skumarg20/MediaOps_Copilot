import type { GoldenCase } from './goldenSet.js';
import type { CaseOutcome } from './harness.js';
import { percent, type StrategyMetrics } from './metrics.js';

export interface ReportInput {
	cases: GoldenCase[];
	metrics: StrategyMetrics[];
	outcomesByStrategy: Map<string, CaseOutcome[]>;
	generatedAt: string;
}

function headline(metrics: StrategyMetrics[]): StrategyMetrics | undefined {
	return metrics.find((entry) => entry.name === 'routed');
}

function metricsTable(metrics: StrategyMetrics[]): string {
	const header =
		'| Strategy | Routing acc. | Answered | Abstained | False answers | Abstention P | Abstention R | F1 | Citation validity |';
	const divider = '|---|---|---|---|---|---|---|---|---|';
	const rows = metrics.map(
		(m) =>
			`| ${m.label} | ${percent(m.routingAccuracy)} | ${m.answered} | ${m.abstained} | ` +
			`**${m.falseAnswers}** (${percent(m.falseAnswerRate)}) | ${percent(m.abstentionPrecision)} | ` +
			`${percent(m.abstentionRecall)} | ${percent(m.abstentionF1)} | ${percent(m.citationValidity)} |`
	);
	return [header, divider, ...rows].join('\n');
}

function failureTable(cases: GoldenCase[], outcomes: CaseOutcome[]): string {
	const byId = new Map(outcomes.map((outcome) => [outcome.caseId, outcome]));
	const rows: string[] = [];

	for (const testCase of cases) {
		const outcome = byId.get(testCase.id);
		if (!outcome) continue;

		const problems: string[] = [];
		if (testCase.shouldAnswer && !outcome.answered) problems.push('abstained when it should have answered');
		if (!testCase.shouldAnswer && outcome.answered) problems.push('**answered when it should have abstained**');
		if (testCase.expectedPath !== 'any' && outcome.pathUsed !== testCase.expectedPath) {
			problems.push(`took ${outcome.pathUsed}, expected ${testCase.expectedPath}`);
		}
		if (testCase.mustCite && outcome.answered && !outcome.citedExpected) {
			problems.push(`missing expected citation ${testCase.mustCite.join(', ')}`);
		}
		if (problems.length === 0) continue;

		rows.push(`| \`${testCase.id}\` | ${testCase.query} | ${problems.join('; ')} |`);
	}

	if (rows.length === 0) return '_No divergences from the golden set._';

	return ['| Case | Query | Divergence |', '|---|---|---|', ...rows].join('\n');
}

export function renderReport(input: ReportInput): string {
	const { cases, metrics, outcomesByStrategy, generatedAt } = input;
	const routed = headline(metrics);
	const routedOutcomes = outcomesByStrategy.get('routed') ?? [];
	const abstainCases = cases.filter((testCase) => !testCase.shouldAnswer).length;
	const answerCases = cases.length - abstainCases;

	const baselineNames = new Set(['always_vector', 'always_vectorless', 'random']);
	const comparisons = metrics
		.filter((entry) => baselineNames.has(entry.name))
		.map((entry) => {
			if (!routed) return `- ${entry.label}: no routed baseline to compare against.`;
			const delta = entry.falseAnswers - routed.falseAnswers;
			const direction =
				delta === 0 ? 'the same number of' : delta > 0 ? `${delta} more` : `${Math.abs(delta)} fewer`;
			const comparator = delta === 0 ? 'as' : 'than';
			return `- **${entry.label}** produced ${direction} false answers ${comparator} the routed system (${entry.falseAnswers} vs ${routed.falseAnswers}), with routing accuracy ${percent(entry.routingAccuracy)}.`;
		});

	const gated = metrics.find((entry) => entry.name === 'adversarial_gated');
	const ungated = metrics.find((entry) => entry.name === 'adversarial_ungated');
	const gateSection =
		gated && ungated
			? `Against a model that fabricates a citation on every turn, the gate withheld
**${ungated.answered - gated.answered}** answers that would otherwise have reached the operator, and cut
false answers from **${ungated.falseAnswers}** to **${gated.falseAnswers}**.

Ungated, **${percent(ungated.citationValidity)}** of the answers it produced carried a citation that
resolved to retrieved evidence — every one was attributed to a source that had never been
retrieved. Gated, all of them were withheld, which is why citation validity reads \`n/a\`:
there were no answers left to score.

That conservatism is the trade. The same run scores an abstention F1 of
${percent(gated.abstentionF1)}, because a model this untrustworthy costs the operator every legitimate
answer as well. The gate is doing exactly what it promises — it is not free.

This is a fabrication-injection test against a deterministic adversary, not a measurement
of how often a real model hallucinates. It bounds what the gate catches when a model does
misbehave, which is the claim the design actually makes.`
			: '_The adversarial pair was not run._';

	return `# System Evaluation — Routing, Abstention & Grounding

<!-- Generated by \`npm run eval\`. Do not edit by hand. -->

Generated ${generatedAt}.

**Golden set:** ${cases.length} labelled queries — ${answerCases} that must be answered,
${abstainCases} that must be abstained on. Labels are written against the fixtures, not
against observed output.

Every strategy runs the **real** routing, retrieval, agent and grounding code. Only the
path-selection policy and the grounding gate are swapped. The model runtime is the
deterministic fake adapter, so results are reproducible and measure retrieval and
gating rather than a particular model's fluency.

## Headline

${
	routed
		? `Routing accuracy **${percent(routed.routingAccuracy)}** over ${routed.routingLabelled} labelled cases.
False answers **${routed.falseAnswers}** of ${abstainCases} cases that should abstain (${percent(routed.falseAnswerRate)}).
Abstention F1 **${percent(routed.abstentionF1)}**. Citation validity **${percent(routed.citationValidity)}**.`
		: 'No routed strategy was run.'
}

## Strategy comparison

${metricsTable(metrics)}

*False answers* — answered a question the golden set says is unanswerable — is the metric
that matters most for an operator at 3am. Every other column is context for it.

${comparisons.join('\n')}

## What the grounding gate is worth

${gateSection}

## Where the routed system diverges from the golden set

${failureTable(cases, routedOutcomes)}

## What each strategy is

${metrics.map((entry) => `- **${entry.label}** — ${entry.description}`).join('\n')}

## Honest interpretation

- The golden set is **hand-labelled against the same fixtures the system serves**. It
  measures whether routing, floors and the grounding gate behave as designed on known
  data. It is not evidence about production traffic.
- Queries are templated in the same register an operator would use, but they are not real
  operator language. The abstention cases are the most transferable part, because
  "should refuse" is a property of the corpus rather than of phrasing.
- The fake model runtime removes generation quality from the measurement. That is
  deliberate: this harness tests the machinery around the model, which is the part the
  design makes claims about. It also means the four faithful rows cannot exercise the
  grounding gate at all — that adapter answers by quoting retrieved evidence, so overlap
  is high and citations always resolve. The adversarial pair exists because of that.
- The baselines share this harness's routing but not a real system's bandit. They measure
  what path selection is worth, not what a deployed alternative would score.
`;
}
